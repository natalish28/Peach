import json
import logging
import os
import sys
import urllib.parse
from email.message import EmailMessage
import boto3

logger = logging.getLogger("report-mailer")
logger.setLevel(logging.INFO)
if not logger.handlers:
    handler_stdout = logging.StreamHandler(sys.stdout)
    handler_stdout.setFormatter(logging.Formatter("%(asctime)s [%(levelname)s] %(message)s"))
    logger.addHandler(handler_stdout)

s3_client = boto3.client("s3")
ses_client = boto3.client("ses")

def handler(event, context):
    logger.info("report-mailer event received: %s", json.dumps(event))
    records = event.get("Records", [])
    if not records:
        logger.warning("No S3 records found in event")
        return {"statusCode": 400, "message": "No records"}

    from_email = os.environ["REPORTS_FROM_EMAIL"]
    to_email = os.environ["REPORTS_TO_EMAIL"]

    for record in records:
        s3_info = record.get("s3", {})
        bucket = s3_info.get("bucket", {}).get("name")
        raw_key = s3_info.get("object", {}).get("key", "")
        key = urllib.parse.unquote_plus(raw_key)

        # Required CloudWatch log line
        logger.info(
            "report-mailer triggered: trigger=s3 bucket=%s key=%s",
            bucket,
            key,
            extra={"trigger": "s3", "bucket": bucket, "key": key}
        )

        if not key.endswith(".csv"):
            logger.info("Skipping non-csv file: %s", key)
            continue

        filename = os.path.basename(key)
        week_name = filename.replace(".csv", "")

        logger.info("Downloading s3://%s/%s...", bucket, key)
        obj = s3_client.get_object(Bucket=bucket, Key=key)
        csv_content = obj["Body"].read()

        logger.info("Building email message for %s...", to_email)
        msg = EmailMessage()
        msg["Subject"] = f"Weekly Report: {week_name}"
        msg["From"] = from_email
        msg["To"] = to_email
        msg.set_content(
            f"Hello,\n\n"
            f"Attached is your automated weekly report for {week_name}.\n\n"
            f"Generated by Amazon EventBridge, SQS, S3, and Amazon SES.\n\n"
            f"Best regards,\nPeach Task Manager"
        )
        msg.add_attachment(
            csv_content,
            maintype="text",
            subtype="csv",
            filename=filename
        )

        logger.info("Sending email via Amazon SES from %s to %s...", from_email, to_email)
        response = ses_client.send_raw_email(
            Source=from_email,
            Destinations=[to_email],
            RawMessage={"Data": msg.as_bytes()}
        )
        logger.info("Email sent successfully! MessageId: %s", response.get("MessageId"))

    return {"statusCode": 200, "message": "Reports emailed successfully"}
